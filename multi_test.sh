#!/bin/sh
# Sandbox test for PROCS (one unit per process) in the hook next to this script.
#
#   sh multi_test.sh              # sandbox lives in $TMPDIR/multi-test
#   SB=/tmp/x sh multi_test.sh
set -u
DIR=$(cd "$(dirname "$0")" && pwd)
HOOK=${HOOK:-$DIR/post-receive}
SB=${SB:-${TMPDIR:-/tmp}/multi-test}; rm -rf "$SB"
mkdir -p "$SB/bin" "$SB/home" "$SB/repos" "$SB/src/app" "$SB/live" "$SB/shared/app"
export HOME="$SB/home" PATH="$SB/bin:$PATH" CALLS="$SB/calls.log"; : > "$CALLS"
cat > "$SB/bin/uv" <<'F'
#!/bin/sh
case "$1" in sync) mkdir -p .venv/bin; printf '#!/bin/sh\n' > .venv/bin/python; chmod +x .venv/bin/python ;; esac
F
cat > "$SB/bin/systemctl" <<'F'
#!/bin/sh
echo "systemctl $*" >> "$CALLS"
F
chmod +x "$SB/bin/uv" "$SB/bin/systemctl"
git init -q --bare -b master "$SB/repos/app.git" 2>/dev/null || git init -q --bare "$SB/repos/app.git"
# hook layout: DEPLOY_ROOT is two levels above the repo dir
mkdir -p "$SB/root/repos" "$SB/root/live" "$SB/root/shared/app"
mv "$SB/repos/app.git" "$SB/root/repos/app"; cp "$HOOK" "$SB/root/post-receive"
ln -sfn ../../../post-receive "$SB/root/repos/app/hooks/post-receive"
R="$SB/root"; U="$HOME/.config/systemd/user"
git -C "$SB/src/app" init -q -b master; git -C "$SB/src/app" config user.email t@e; git -C "$SB/src/app" config user.name T
echo 'x' > "$SB/src/app/main.py"; echo 'v=1' > "$SB/src/app/uv.lock"
push() { git -C "$SB/src/app" add -A; git -C "$SB/src/app" commit -qm "$1" --allow-empty; git -C "$SB/src/app" push -q "$R/repos/app" master 2>&1 | sed 's/^/  /'; }
ok() { echo "PASS $1"; }; bad() { echo "FAIL $1"; F=1; }; F=0
chk() { if grep -qF -- "$2" "$3" 2>/dev/null; then ok "$1"; else bad "$1 (no '$2' in $3)"; fi; }
no()  { if [ -e "$2" ]; then bad "$1 ($2 exists)"; else ok "$1"; fi; }

echo "== 1. no PROCS: single unit, as before"
push one
[ -f "$U/app.service" ] && ok "main unit written" || bad "main unit"
ls "$U" | grep -q -- '-' && bad "extra unit appeared" || ok "no extra units"
sed -n '1,4p' "$U/app.service" | grep -q '^After=network.target$' && ok "no PartOf in main" || bad main

echo "== 2. add two procs"
cat > "$R/shared/app/deploy.conf" <<'C'
PROCS="worker beat"
EXEC_worker="{live_curr}/.venv/bin/python -m myapp.worker"
EXEC_beat="{live_curr}/.venv/bin/python -m myapp.beat"
C
: > "$CALLS"; push two
chk "worker unit" "ExecStart=$R/live/app!CURRENT/.venv/bin/python -m myapp.worker" "$U/app-worker.service"
chk "worker PartOf" "PartOf=app.service" "$U/app-worker.service"
chk "worker marker" "# proc-of: app" "$U/app-worker.service"
chk "beat unit" "ExecStart=$R/live/app!CURRENT/.venv/bin/python -m myapp.beat" "$U/app-beat.service"
chk "worker enabled" "systemctl --user enable app-worker.service" "$CALLS"
chk "worker started" "systemctl --user start app-worker.service" "$CALLS"
chk "beat started" "systemctl --user start app-beat.service" "$CALLS"
grep -n 'restart app.service\|start app-' "$CALLS" | head -5

echo "== 3. redeploy: no rewrite, no re-enable"
: > "$CALLS"; push three
chk "main restarted" "systemctl --user restart app.service" "$CALLS"
grep -q 'enable' "$CALLS" && bad "re-enabled" || ok "not re-enabled"
grep -q 'Installing app-worker' "$CALLS" && bad rewrite || ok "unit unchanged, not rewritten"

echo "== 4. drop beat: stale unit removed, worker kept"
sed -i 's/^PROCS=.*/PROCS="worker"/' "$R/shared/app/deploy.conf"
: > "$CALLS"; push four
no "beat unit removed" "$U/app-beat.service"
chk "beat disabled" "systemctl --user disable --now app-beat.service" "$CALLS"
[ -f "$U/app-worker.service" ] && ok "worker kept" || bad "worker gone"

echo "== 5. other app's unit with same prefix is never touched"
printf '# Generated by post-receive - edit x, not this file.\n[Unit]\nDescription=other\n' > "$U/app-other.service"
: > "$CALLS"; push five
[ -f "$U/app-other.service" ] && ok "app-other.service survives cleanup" || bad "deleted another app's unit"
sed -i 's/^PROCS=.*/PROCS="worker other"/' "$R/shared/app/deploy.conf"
echo 'EXEC_other="/bin/true"' >> "$R/shared/app/deploy.conf"
push six | grep -q 'DEPLOY FAILED' && ok "refuses to overwrite unit it did not generate" || bad "overwrote foreign unit"

echo "== 6. bad name / missing exec"
printf 'PROCS="bad-name"\n' > "$R/shared/app/deploy.conf"
push seven | grep -q "bad process name" && ok "bad name rejected" || bad "bad name accepted"
printf 'PROCS="w"\n' > "$R/shared/app/deploy.conf"
push eight | grep -q "EXEC_w is empty" && ok "missing EXEC_ rejected" || bad "missing exec accepted"
exit $F
